"""A Pocket's race for the simulation: the header firmware/sim_replay_data.h from the debug.txt the core wrote.

Usage: python -I tools/s2/replay_header.py <debug.txt> <out.h> [ff] [show_from] [damages] [view]
  The debug.txt has the race's choices ("menu: race T4 CONDOR2 1L ROOKIE AUTO") and the changes of the buttons of its first minute
  ("I812 0020": the race step they took effect at, the buttons in hex; firmware/viewer.c INPUT_LOG_MAX). The race is the same whatever the
  frames took, so the simulation (the firmware itself, cycle by cycle) runs the same race from them: build the firmware with
  `tools/fw.sh EXTRA_CFLAGS=-DS2_SIM_REPLAY=1 TAG=replay` (viewer.c: the physics alone up to step `ff`, then the frames, each from
  step `show_from` on with its line "L..." in the simulation's debug.txt, as the Pocket's late frames have it) and run it with
  tools/s2/sim_race.sh on a track image made with S2CARS for the same grid (tools/s2/make_track_s2.py).
  damages: the GAME SETTINGS' DAMAGES (0 off, 1 on: the Pocket's CHOICE.DAT, main part byte 10 of the settings), view: its view (3 BACK).
The header stays out of the repository (it is somebody's play; .gitignore).
"""
import re
import sys

TEAMS = ["CONDOR", "ANGELS", "WASP", "ZEUS"]
LAPS = [1, 3, 5, 10]
SKILLS = ["ROOKIE", "NORMAL", "PRO"]


def main():
    src, out = sys.argv[1], sys.argv[2]
    ff = int(sys.argv[3]) if len(sys.argv) > 3 else 950
    show = int(sys.argv[4]) if len(sys.argv) > 4 else ff + 32
    damages = int(sys.argv[5]) if len(sys.argv) > 5 else 0
    view = int(sys.argv[6]) if len(sys.argv) > 6 else 3
    text = open(src, "rb").read().replace(b"\0", b"").decode("latin1")
    m = None
    for line in text.split("\n"):
        mm = re.match(r"menu: race T(\d) ([A-Z]+?)(\d) (\d+)L (\w+) (AUTO|MAN)", line)
        if mm:
            m = mm                                   # (the last start in the log)
    if not m:
        sys.exit("no 'menu: race ...' line in " + src)
    track, team, car, laps, skill, gears = int(m[1]), TEAMS.index(m[2]) + 1, int(m[3]), int(m[4]), SKILLS.index(m[5]), m[6]
    keys = [(int(a), int(b, 16)) for a, b in re.findall(r"^I(\d+) ([0-9a-f]+)$", text, re.M)]
    if not keys or keys[0][0] != 0:
        sys.exit("the buttons' lines do not start at step 0")
    with open(out, "w", newline="\n") as f:
        f.write("/* generated by tools/s2/replay_header.py from %s: do not commit */\n" % src.replace("\\", "/").split("/")[-1])
        f.write("#define SIM_REPLAY_TRACK %d\n#define SIM_REPLAY_TEAM %d\n#define SIM_REPLAY_CAR %d\n" % (track, team, car))
        f.write("#define SIM_REPLAY_LAPS_INDEX %d\n#define SIM_REPLAY_SKILL %d\n#define SIM_REPLAY_MANUAL %d\n" % (LAPS.index(laps), skill, gears == "MAN"))
        f.write("#define SIM_REPLAY_DAMAGES %d\n#define SIM_REPLAY_VIEW %d\n" % (damages, view))
        f.write("#define SIM_REPLAY_FF %d\n#define SIM_REPLAY_SHOW_FROM %d\n" % (ff, show))
        f.write("static const uint32_t SIM_REPLAY[][2] = {\n")
        for st, k in keys:
            f.write("    { %d, 0x%x },\n" % (st, k))
        f.write("};\n")
    print("track %d team %d car %d, %d laps, %s, %s; %d changes of the buttons, the last at step %d; fast to step %d, lines from %d"
          % (track, team, car, laps, m[5], gears, len(keys), keys[-1][0], ff, show))


main()
